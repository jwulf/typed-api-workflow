import fs from 'fs';
import path from 'path';
import yaml from 'yaml';

const ROOT = path.resolve(process.cwd());
const SPEC = path.resolve(ROOT, '../../rest-api.domain.yaml');
const OUT_DIR = path.join(ROOT, 'src/newgen');
const SERVICES_FILE = path.join(OUT_DIR, 'services.gen.ts');
const REQUEST_FILE = path.join(OUT_DIR, 'core', 'request.ts');
const OPENAPI_FILE = path.join(OUT_DIR, 'core', 'OpenAPI.ts');

function run() {
  if (!fs.existsSync(SERVICES_FILE)) { console.warn('[newgen-postprocess] services.gen.ts missing'); return; }
  const spec = yaml.parse(fs.readFileSync(SPEC, 'utf8'));
  const eventualOps: { name: string; method: string; path: string }[] = [];
  for (const [p, item] of Object.entries<any>(spec.paths || {})) {
    for (const [verb, op] of Object.entries<any>(item || {})) {
      if (op && op['x-eventually-consistent']) eventualOps.push({ name: op.operationId, method: verb.toUpperCase(), path: p });
  }
  let services = fs.readFileSync(SERVICES_FILE, 'utf8');
  if (!services.includes("eventualPoll") && eventualOps.length) {
    services = services.replace("// This file is auto-generated by @hey-api/openapi-ts", `// This file is auto-generated by @hey-api/openapi-ts\n// Modified by postprocess-newgen for eventual consistency wrappers\nimport { eventualPoll } from '../runtime/eventual';`);
  }
  const metaEntries = eventualOps.map(e=> `${e.name}: { method: '${e.method}', path: '${e.path}', eventuallyConsistent: true }`);
  if (metaEntries.length && !services.includes('export const operationMeta')) {
    services += `\nexport const operationMeta = {\n${metaEntries.map(e=>'  '+e+',').join('\n')}\n} as const;\n`;
  }
  for (const eo of eventualOps) {
    const fnRegex = new RegExp(`export const ${eo.name} = \\(`);
    if (!fnRegex.test(services)) continue;
    if (services.includes(`_raw_${eo.name}`)) continue;
    services = services.replace(fnRegex, `export const _raw_${eo.name} = (`);
    const terminator = new RegExp(`export const _raw_${eo.name} = [\\s\\S]*?};`);
    const match = services.match(terminator);
    if (match) {
      const wrapper = `\n/** Eventually consistent wrapper */\nexport const ${eo.name} = (data?: any, consistency?: { waitUpToMs: number; pollIntervalMs?: number; predicate?: (r:any)=>boolean }) => {\n  if (!consistency) return _raw_${eo.name}(data);\n  const invoke = () => _raw_${eo.name}(data);\n  return eventualPoll('${eo.name}', ${eo.method==='GET'}, invoke, consistency as any);\n};\n`;
      services = services.replace(match[0], match[0] + wrapper);
    }
  }
  // Inject operationId into all __request calls if not present
  services = services.replace(/__request\(OpenAPI, \{(\s*?)method:/g, (m, ws) => `__request(OpenAPI, {${ws}operationId: '__AUTO__', method:`);
  // Replace placeholder with actual operation name using preceding export const pattern
  services = services.replace(/export const (_raw_)?([a-zA-Z0-9_]+) = .*?__request\(OpenAPI, \{([\s\S]*?)operationId: '__AUTO__'/g, (full, rawPrefix, name, before) => {
    return full.replace("operationId: '__AUTO__'", `operationId: '${name.replace(/^_raw_/, '')}'`);
  });
  fs.writeFileSync(SERVICES_FILE, services, 'utf8');
  console.log(`[newgen-postprocess] Wrapped ${eventualOps.length} eventual operations.`);

  // Patch request.ts for verbose variant reporting (createProcessInstance + evaluateDecision)
  if (fs.existsSync(REQUEST_FILE)) {
    let reqSrc = fs.readFileSync(REQUEST_FILE, 'utf8');
    if (!reqSrc.trim()) {
      reqSrc = `// synthesized minimal request runtime by postprocess-newgen\n// anchor for verbose injection\n// let msg = \`request.validation <operationId> -> issues: <issues>\`;\nexport const request = () => { throw new Error('request runtime not generated'); };`;
      fs.writeFileSync(REQUEST_FILE, reqSrc, 'utf8');
      console.log('[newgen-postprocess] Synthesized minimal request.ts');
    }
    }
  }

  // Patch OpenAPI.ts to add extended config fields (logger, validation, fetch) idempotently
  if (fs.existsSync(OPENAPI_FILE)) {
    let openapi = fs.readFileSync(OPENAPI_FILE, 'utf8');
    if (!openapi.includes('logger?:')) {
      openapi = openapi.replace(/export type OpenAPIConfig = {/, match => `${match}\n\t/** Added by postprocess-newgen */\n\tlogger?: (level: 'debug' | 'warn' | 'error', message: string, meta?: any) => void;\n\tvalidationMode?: 'none' | 'warn' | 'strict';\n\tvalidation?: { req?: 'none' | 'warn' | 'strict'; res?: 'none' | 'warn' | 'strict' };\n\tfetch?: typeof fetch;`);
      // Add default values in exported OpenAPI instance
      openapi = openapi.replace(/export const OpenAPI: OpenAPIConfig = {/, match => `${match}\n\tlogger: undefined,\n\tvalidationMode: 'warn',\n\tvalidation: { req: 'warn', res: 'none' },\n\tfetch: undefined,`);
      fs.writeFileSync(OPENAPI_FILE, openapi, 'utf8');
      console.log('[newgen-postprocess] Augmented OpenAPI.ts with extended config fields');
    }
  }
  
  // Generate validation-schemas.ts deterministically (request/response validators)
  const RUNTIME_DIR = path.join(OUT_DIR, 'runtime');
  fs.mkdirSync(RUNTIME_DIR, { recursive: true });
  const validationFile = path.join(RUNTIME_DIR, 'validation-schemas.ts');
  const validationSource = `/** @generated via postprocess-newgen */\nexport interface ValidationIssue { path: string; code: string; message: string; }\ntype ValidatorFn = (value: any) => ValidationIssue[];\nfunction variantOneOf(fields: [string,string], idNames: [string,string]): ValidatorFn {\n  return (v: any) => {\n    const issues: ValidationIssue[] = [];\n    if (v === null || typeof v !== 'object') { issues.push({ path: '', code: 'TYPE', message: 'Expected object' }); return issues; }\n    const [a,b] = fields; const [an,bn] = idNames; const byA = a in v; const byB = b in v;\n    if (!byA && !byB) issues.push({ path: '', code: 'ONE_OF', message: 'Must supply ' + a + ' or ' + b });\n    if (byA && byB) issues.push({ path: '', code: 'ONE_OF', message: 'Provide only one of ' + a + ' or ' + b });\n    return issues;\n  };\n}\nconst validateProcessInstanceCreationInstruction = variantOneOf(['processDefinitionId','processDefinitionKey'], ['ProcessInstanceCreationInstructionById','ProcessInstanceCreationInstructionByKey']);\nconst validateDecisionEvaluationInstruction = variantOneOf(['decisionDefinitionId','decisionDefinitionKey'], ['DecisionEvaluationById','DecisionEvaluationByKey']);\nexport const requestValidators: Record<string, ValidatorFn> = {\n  createProcessInstance: validateProcessInstanceCreationInstruction,\n  evaluateDecision: validateDecisionEvaluationInstruction,\n};\nfunction requiredFields(fields: string[]): ValidatorFn { return (value: any) => { const issues: ValidationIssue[] = []; if (value === null || typeof value !== 'object') { issues.push({ path: '', code: 'TYPE', message: 'Expected object response' }); return issues; } for (const f of fields) { if (!(f in value)) issues.push({ path: f, code: 'REQUIRED', message: 'Missing required field' }); } return issues; }; }\nexport const responseValidators: Record<string, ValidatorFn> = {\n  createProcessInstance: requiredFields(['processDefinitionId','processDefinitionKey','processInstanceKey','variables']),\n  getProcessInstance: requiredFields(['processDefinitionId','processDefinitionKey','processInstanceKey','state']),\n};\n`;
  fs.writeFileSync(validationFile, validationSource, 'utf8');
  console.log('[newgen-postprocess] Wrote validation-schemas.ts');
}

run();
